/* ---- 触摸屏中断 (GPIO EXTI) ---- */
void GTP_IRQHandler(void)
{
	if(__HAL_GPIO_EXTI_GET_IT(GTP_INT_GPIO_PIN) != RESET)
	{
		GTP_TouchProcess();
		__HAL_GPIO_EXTI_CLEAR_IT(GTP_INT_GPIO_PIN);
	}
}

